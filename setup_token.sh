#!/data/data/com.termux/files/usr/bin/bash

echo ""
echo "==========================================="
echo "  SHRUTI U.K. CHAT - TOKEN SETUP"
echo "==========================================="
echo ""
echo "Apna Telegram bot token paste karo"
echo "(BotFather se mila tha, jaise: 8925120670:AAHxxxxx...)"
echo ""
read -p "📝 Token: " USER_TOKEN

if [ -z "$USER_TOKEN" ]; then
    echo "❌ Token khaali hai! Dobara chalao."
    exit 1
fi

# Check token format (number:letters)
if [[ ! "$USER_TOKEN" =~ ^[0-9]+:[A-Za-z0-9_-]+$ ]]; then
    echo "⚠️  Warning: Token format theek nahi lag raha."
    echo "   Sahi format: 8925120670:AAHxxxxxxxxxxxx"
    echo ""
    read -p "Phir bhi save karein? (y/n): " CONFIRM
    if [ "$CONFIRM" != "y" ]; then
        exit 1
    fi
fi

# Save to config.dart
cat > lib/config.dart << EOF
// ============================================
// SHRUTI U.K. CHAT - TELEGRAM CONFIG
// Auto-generated by setup_token.sh
// ============================================

const String TG_TOKEN = '$USER_TOKEN';
const String TG_CHAT_ID = '8606011679';
EOF

echo ""
echo "✅ Token save ho gaya config.dart me!"
echo ""
echo "🔍 Verify:"
echo "-------------------------------------------"
cat lib/config.dart
echo "-------------------------------------------"
echo ""
echo "🚀 Ab push karo:"
echo "   git add . && git commit -m 'Token setup' && git push"
echo ""
